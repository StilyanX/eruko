// Hides: what the page fetches at once. The app has no build, so the browser finds each module
// only once the one that imports it has arrived: on a slow connection the chain of round trips,
// not the bytes, decides how long the first page takes. This writes into src/index.html, between
// its two preload markers, a preload of every stylesheet style/main.css imports (so they arrive
// with it, not one round trip after), and one <link rel=modulepreload> for every
// module the first screen needs (the start-up script, the shell, each unit's manifest from the
// unit list, and everything they import statically), so the browser fetches them all at once.
// (The record's SQLite is loaded by its worker, which a page's preload does not reach.) A unit's
// pages load when opened, so they are left out. Run after changing an import of the shell, the
// parts or a manifest: node scripts/gen/preload.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { FOLDERS } from '../../src/shell/units.gen.js'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const SRC = path.join(ROOT, 'src')
const PAGE = path.join(SRC, 'index.html')
const MAIN = path.join(SRC, 'shell', 'main.js')
const START = '<!-- preload: generated by scripts/gen/preload.mjs -->'
const END = '<!-- /preload -->'

const STATIC = /(?:import|export)[^'"]*?from\s*['"]([^'"]+)['"]|^\s*import\s*['"]([^'"]+)['"]/gm
const DYNAMIC = /import\s*\(\s*['"]([^'"]+)['"]\s*\)/g

/**
 * Every module reached from `file` by static imports; dynamic imports are followed only from the
 * start-up script (the shell it opens once the record is read).
 * @param {string} file
 * @param {Set<string>} seen
 */
function walk(file, seen) {
  if (seen.has(file)) return
  seen.add(file)
  const src = readFileSync(file, 'utf8')
  const specs = [...src.matchAll(STATIC)].map(m => m[1] ?? m[2] ?? '')
  if (file === MAIN) specs.push(...[...src.matchAll(DYNAMIC)].map(m => m[1] ?? ''))
  for (const spec of specs) if (spec.startsWith('.')) walk(path.resolve(path.dirname(file), spec), seen)
}

/** @type {Set<string>} */
const seen = new Set()
walk(MAIN, seen)
for (const unit of FOLDERS) walk(path.join(SRC, 'units', unit, 'manifest.js'), seen)
const href = (/** @type {string} */ f) => path.relative(SRC, f).split(path.sep).join('/')
const modules = [...seen].map(href).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
/**
 * Every stylesheet a stylesheet imports, at any depth, in order.
 * @param {string} file
 * @returns {string[]}
 */
const importsOfCss = file =>
  [...readFileSync(file, 'utf8').matchAll(/@import\s+['"]([^'"]+)['"]/g)].flatMap(m => {
    const target = path.resolve(path.dirname(file), m[1] ?? '')
    return [target, ...importsOfCss(target)]
  })
const sheets = importsOfCss(path.join(SRC, 'style', 'main.css')).map(href)
const lines = [
  START,
  ...sheets.map(m => `    <link rel="preload" as="style" href="${m}">`),
  ...modules.map(m => `    <link rel="modulepreload" href="${m}">`),
  `    ${END}`
]
const page = readFileSync(PAGE, 'utf8')
const block = lines.join('\n')
const at = page.indexOf(START)
const next =
  at >= 0
    ? page.slice(0, at) + block + page.slice(page.indexOf(END) + END.length)
    : page.replace('</head>', `    ${block}\n</head>`)
writeFileSync(PAGE, next)
console.log(`gen-preload: ${modules.length} modules`)
