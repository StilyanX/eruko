import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync } from 'node:fs'
import { piecesIn } from '../src/kernel/maths-text.logic.js'
import { mathsUnits } from '../scripts/lib/maths-units.mjs'

// Every topic and bank file of the maths units has its MathML file (scripts/gen/mathml.mjs), made
// from the file as it is now, holding every formula piece the screens set from it.

/**
 * @param {unknown} v
 * @returns {string[]}
 */
const strings = v =>
  typeof v === 'string'
    ? [v]
    : Array.isArray(v)
      ? v.flatMap(strings)
      : v !== null && typeof v === 'object'
        ? Object.values(v).flatMap(strings)
        : []

for (const unit of mathsUnits())
  for (const kind of ['topics', 'bank'])
    test(`${unit} ${kind}: each file's MathML is made from it as it is and holds every formula`, async () => {
      const dir = new URL(`../src/units/${unit}/content/${kind}/`, import.meta.url)
      for (const name of readdirSync(dir).filter(n => n.endsWith('.js') && n !== 'index.js')) {
        const source = readFileSync(new URL(name, dir), 'utf8')
        const genUrl = new URL(
          `../src/units/${unit}/content/mathml/${kind}/${name.replace(/\.js$/, '.gen.js')}`,
          import.meta.url
        )
        const gen = readFileSync(genUrl, 'utf8')
        const sha = createHash('sha256').update(source).digest('hex')
        assert.ok(
          gen.startsWith('// Generated by scripts/gen/mathml.mjs'),
          `${unit}/${kind}/${name}: not generated`
        )
        assert.ok(
          gen.split('\n')[1]?.includes(sha),
          `${unit}/${kind}/${name} changed: run node scripts/gen/mathml.mjs`
        )
        /** @type {Record<string, string>} */
        const map = (await import(genUrl.href)).default
        const mod = await import(new URL(name, dir).href)
        for (const piece of new Set(strings(Object.values(mod)).flatMap(piecesIn)))
          assert.ok(piece in map, `${unit}/${kind}/${name}: no MathML for ${JSON.stringify(piece)}`)
      }
    })
